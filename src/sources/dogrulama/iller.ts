export function plakaIl(kod: number): string | null {
  if (!Number.isInteger(kod) || kod < 1 || kod > ILLER.length) return null;
  return ILLER[kod - 1] ?? null;
}

/** Case- and diacritic-tolerant lookup: "istanbul", "İSTANBUL", "Istanbul" all resolve. */
export function ilPlaka(ad: string): number | null {
  const anahtar = sadelestir(ad);
  const i = ILLER.findIndex((il) => sadelestir(il) === anahtar);
  return i === -1 ? null : i + 1;
}

function sadelestir(s: string): string {
  return s
    .trim()
    .replace(/İ/g, 'i')
    .replace(/I/g, 'ı')
    .toLowerCase()
    .replace(/[âîû]/g, (c) => ({ â: 'a', î: 'i', û: 'u' })[c] ?? c)
    .replace(/ç/g, 'c')
    .replace(/ğ/g, 'g')
    .replace(/ı/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ş/g, 's')
    .replace(/ü/g, 'u');
}
